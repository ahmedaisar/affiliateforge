/**
 * Mason, slice one: the static storefront generator.
 * Reads the frozen catalogue + the brief's evidence rows + the operator's look
 * choice and writes a real, self-contained static site into outDir.
 *
 * Hard invariants (verified byte-offset, not visual):
 *  - the FTC disclosure paragraph precedes the first /go/ link in document order
 *  - no merchant price is rendered (we hold no price capture — never invent one)
 *  - every evidence row appears with its source URL and read-on date
 *  - all dynamic strings are HTML-escaped
 */
import { DatabaseSync } from "node:sqlite";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const esc = (v) =>
  String(v ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");

const escUrl = (v) => {
  try {
    const u = new URL(String(v));
    return (u.protocol === "http:" || u.protocol === "https:") ? esc(u.href) : "";
  } catch { return ""; }
};

const SAFE_ID = /^[a-z0-9][a-z0-9-]{1,60}$/;

export function buildStore(dbPath, storeId, outDir) {
  if (!SAFE_ID.test(storeId)) throw new Error("store id contains unsafe characters");
  const resolved = path.resolve(outDir, storeId);
  const db = new DatabaseSync(dbPath, { readOnly: true });
  try {
    const store = db.prepare("SELECT id, domain, niche FROM stores WHERE id = ?").get(storeId);
    if (!store) throw new Error("no such store");
    const products = db.prepare(
      "SELECT id, name, merchant, commission, position FROM catalogue WHERE store_id = ? AND removed = 0 ORDER BY position"
    ).all(storeId);
    const meta = db.prepare("SELECT title FROM brief_meta WHERE store_id = ?").get(storeId);
    const evidence = db.prepare(
      "SELECT claim, source, read_on AS readOn, kind FROM brief_evidence WHERE store_id = ?"
    ).all(storeId);
    return generate({ store, products, meta: meta ?? null, evidence, outDir: resolved });
  } finally {
    db.close();
  }
}

function generate({ store, products, meta, evidence, outDir }) {
  mkdirSync(outDir, { recursive: true });
  const storeName = esc(store.domain);
  const niche = esc(store.niche);
  const year = new Date().getUTCFullYear();

  const productCards = products.length === 0
    ? `<p class="muted">No offers approved yet — this page is honest about being empty.</p>`
    : products.map((p) => `
      <li class="card">
        <a class="product-name" href="/go/${esc(store.id)}/${encodeURIComponent(p.id)}" rel="sponsored noopener">${esc(p.name)}</a>
        <div class="meta"><span>${esc(p.merchant)}</span> · <span>Commission ${esc(String(p.commission))}%</span></div>
        <div class="price-note">Price shown by the merchant at checkout; we keep no stale price on this page.</div>
      </li>`).join("\n");

  const indexHtml = `<!doctype html>
<html lang="en-gb">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${storeName} — ${niche}</title>
<meta name="description" content="A short list of ${niche} products, with links we earn a commission on.">
<style>
  body { font-family: Georgia, 'Times New Roman', serif; color:#1f2a1f; background:#faf7f1; margin:0; }
  main { max-width: 720px; margin: 0 auto; padding: 32px 20px; }
  .disclosure { font-size:.85rem; background:#fff3d6; border:1px solid #e0c878; padding:10px 14px; border-radius:6px; margin-bottom:24px; }
  h1 { font-size:1.6rem; margin:0 0 4px; }
  .sub { color:#4a5a4a; font-size:.95rem; margin-bottom:20px; }
  ul { list-style:none; padding:0; }
  .card { background:#fff; border:1px solid #e7e2d4; border-radius:6px; padding:12px 14px; margin-bottom:10px; }
  .product-name { font-size:1.05rem; font-weight:bold; color:#0f3a1f; text-decoration:none; }
  .product-name:hover { text-decoration:underline; }
  .meta { font-size:.85rem; color:#4a5a4a; margin:4px 0; }
  .price-note { font-size:.8rem; color:#6b7263; font-style:italic; }
  footer { font-size:.8rem; color:#6b7263; border-top:1px solid #e7e2d4; margin-top:40px; padding-top:16px; }
  .muted { color:#6b7263; font-style:italic; }
</style>
</head>
<body>
<main>
  <p class="disclosure">We earn a commission on some links on this page at no extra cost to you. Prices are set by the merchant.</p>
  <h1>${storeName}</h1>
  <p class="sub">${niche}</p>
  <ul>${productCards}</ul>
  <footer>
Sample storefront generated by Cairn — the method and sources are in <a href="/method.html">method</a>.<br>
${year} ${storeName}
  </footer>
</main>
</body>
</html>`;

  const evidenceRows = evidence.length === 0
    ? `<li>No evidence on file — treat every claim on this page as unverified.</li>`
    : evidence.map((e) => `
      <li><strong>${esc(e.claim)}</strong><br>
        <a href="${escUrl(e.source)}" rel="external nofollow noopener">${esc(e.source)}</a><br>
        Read on ${esc(e.readOn)} · kind: ${esc(e.kind)}</li>`).join("\n");

  const methodHtml = `<!doctype html>
<html lang="en-gb">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Method — ${storeName}</title>
<style>
  body { font-family: Georgia, serif; color:#1f2a1f; background:#faf7f1; margin:0; }
  main { max-width: 720px; margin: 0 auto; padding: 32px 20px; }
  h1 { font-size:1.4rem; }
  ul { padding-left: 18px; }
  li { margin-bottom:14px; }
  a { color:#0f3a1f; }
  .note { font-size:.85rem; color:#6b7263; border-left:2px solid #e0c878; padding-left:12px; }
</style>
</head>
<body>
<main>
  <h1>Method</h1>
  <p class="note">Everything on this page is traceable: each claim cites a source and the date it was read. Nothing here is invented; missing evidence is shown as missing.</p>
  <ul>${evidenceRows}</ul>
  <p><a href="/">← back to ${storeName}</a></p>
</main>
</body>
</html>`;

  const notFoundHtml = `<!doctype html>
<html lang="en-gb"><head><meta charset="utf-8"><title>Not found — ${storeName}</title>
<style>body{font-family:Georgia,serif;background:#faf7f1;color:#1f2a1f;padding:40px 20px}main{max-width:720px;margin:0 auto}a{color:#0f3a1f;}</style>
</head><body><main><h1>Not found</h1><p>The page you asked for does not exist. <a href="/">Back to ${storeName}</a>.</p></main></body></html>`;

  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>/index.html</loc></url>
  <url><loc>/method.html</loc></url>
</urlset>`;

  writeFileSync(path.join(outDir, "index.html"), indexHtml);
  writeFileSync(path.join(outDir, "method.html"), methodHtml);
  writeFileSync(path.join(outDir, "404.html"), notFoundHtml);
  writeFileSync(path.join(outDir, "sitemap.xml"), sitemap);

  return {
    outDir,
    files: ["index.html", "method.html", "404.html", "sitemap.xml"],
    products: products.length,
    evidence: evidence.length,
  };
}
